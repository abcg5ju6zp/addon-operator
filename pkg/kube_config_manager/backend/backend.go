package backend

import (
	"context"
	"errors"

	"github.com/flant/addon-operator/pkg/kube_config_manager/config"
	"github.com/flant/addon-operator/pkg/utils"
)

// ErrCommitNotConfirmed is returned when the result of a write request is
// ambiguous (timeout, connection reset, 5xx, ...) and the follow-up read can
// neither confirm nor deny that the commit landed. No checksum must be
// published for such commits: the next reconcile re-runs the hooks.
var ErrCommitNotConfirmed = errors.New("config commit result is not confirmed")

// ErrCommitConflict is returned when the resource keeps changing concurrently
// and all commit attempts were rejected with an optimistic-concurrency
// conflict.
var ErrCommitConflict = errors.New("config commit conflicts with a concurrent update")

// CommitRequest is a hook values writeback with its concurrency context.
type CommitRequest struct {
	// Key is the section key: utils.GlobalValuesKey ("global") or a module
	// name in kebab-case.
	Key string

	// Values is the target section content produced by the hook. Both the
	// root-wrapped form ({"myModule": {...}}) and the plain section map are
	// accepted.
	Values utils.Values

	// Patch contains only the operations the hook actually emitted for the
	// section. Conflicts are judged for these paths alone; external updates of
	// other paths are preserved. Nil means a legacy whole-section overwrite:
	// no conflict detection is performed.
	Patch *utils.ValuesPatch

	// BaselineValues is the section content (without the root key) as seen by
	// the hook, i.e. the "base" of the three-way merge. When nil, the current
	// remote content is used as the baseline.
	BaselineValues utils.Values

	// BaselineResourceVersion is the resourceVersion of the backend resource
	// the hook read its baseline from. When it differs from the remote
	// version, the commit is merged instead of being written blindly.
	BaselineResourceVersion string

	// CommitID is the stable identity of the write. It is generated once and
	// reused across retries and outcome-confirmation reads, so an ambiguous
	// response can be reconciled afterwards. Generated by the backend when
	// empty.
	CommitID string
}

// CommitOutcome is the confirmed state of a committed writeback.
type CommitOutcome struct {
	// DataKey is the ConfigMap key the section is stored under
	// ("global" or the camelCased module name).
	DataKey string

	// ResourceVersion of the backend resource containing the commit.
	ResourceVersion string

	// Checksum of the committed section, calculated with the same rules as
	// checksums of informer snapshots.
	Checksum string

	// Values is the committed section content without the root key,
	// normalized through a YAML round-trip exactly like remote content.
	Values utils.Values

	// ConflictPaths lists hook patch paths kept as remote values because of a
	// same-path conflict.
	ConflictPaths []string

	// Merged is true when remote content changed since the read baseline and
	// the target was merged with it instead of being written directly.
	Merged bool
}

// ConfigHandler load and saves(optional) configuration for module
type ConfigHandler interface {
	// StartInformer starts backend watcher which follows a resource, parse and send module/modules values for kube_config_manager
	StartInformer(ctx context.Context, eventC chan config.Event)

	// LoadConfig loads initial modules config before starting the informer
	LoadConfig(ctx context.Context, modulesNames ...string) (*config.KubeConfig, error)

	// CommitConfigValues writes hook-produced values for a section using
	// optimistic concurrency: it retries resourceVersion conflicts with a
	// three-way merge, preserves concurrent external updates of other paths,
	// keeps remote values for same-path conflicts and confirms ambiguous write
	// results with a follow-up read.
	CommitConfigValues(ctx context.Context, req CommitRequest) (*CommitOutcome, error)
}
